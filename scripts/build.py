"""Build the standalone EXE and the portable full-model bundle.

    python scripts/build.py --mode standalone   # true single-file EXE (light models)
    python scripts/build.py --mode portable    # folder + all four engines
    python scripts/build.py --mode all         # both, plus ZIP archives

Requires PyInstaller, PySide6, sherpa-onnx, soundfile, sounddevice, pywin32,
pylnk3, Pillow in the active Python environment.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import textwrap
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PKG = SRC / "voxscribe"
RESOURCES = PKG / "resources"
BUILD = ROOT / "_build"
DIST = ROOT / "dist"
MODELS = ROOT / "models"
ENTRY = PKG / "__main__.py"

LIGHT_MODEL_FILES = (
    "sensevoice/model.int8.onnx", "sensevoice/tokens.txt", "sensevoice/LICENSE",
    "paraformer/model.int8.onnx", "paraformer/tokens.txt",
    "vad/silero_vad.onnx", "manifest.json",
)


def ensure_icon() -> Path:
    RESOURCES.mkdir(parents=True, exist_ok=True)
    p = RESOURCES / "icon.ico"
    if p.is_file():
        return p
    from PIL import Image, ImageDraw

    size = 256
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((8, 8, 248, 248), radius=52, fill=(24, 28, 38, 255),
                        outline=(59, 130, 246, 255), width=6)
    # Stylised waveform / "V"
    bars = [(46, 92, 40), (74, 62, 100), (102, 40, 140), (130, 78, 100),
            (158, 104, 48), (186, 86, 76), (214, 120, 24)]
    for x, top, height in bars:
        d.rounded_rectangle((x, size // 2 - height // 2 + (top - 100) // 6,
                             x + 16, size // 2 + height // 2 + (top - 100) // 6),
                            radius=8, fill=(125, 211, 252, 255))
    d.line([(52, 196), (104, 208), (128, 154), (152, 208), (204, 196)],
           fill=(52, 211, 153, 255), width=12, joint="curve")
    img.save(p, format="ICO",
             sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64),
                    (128, 128), (256, 256)])
    print("Icon generated:", p)
    return p


def find_ffmpeg() -> Path:
    p = shutil.which("ffmpeg")
    if p:
        return Path(p)
    try:
        import imageio_ffmpeg
        return Path(imageio_ffmpeg.get_ffmpeg_exe())
    except Exception as exc:
        raise SystemExit(f"ffmpeg.exe not found and imageio-ffmpeg unavailable: {exc}")


def ensure_ffmpeg() -> Path:
    """Bundle ffmpeg under a canonical lowercase name.

    Upstream builds sometimes ship ``ffmpeg.EXE``.  PyInstaller keeps that
    exact spelling, so the archive would contain ``_internal/ffmpeg.EXE``
    while the runtime probes ``ffmpeg.exe``.  Windows ignores case, but a
    case-sensitive extraction (or a case-sensitive filesystem) would not.
    Normalising here makes source, bundle and documentation agree.
    """
    src = find_ffmpeg()
    out_dir = BUILD / "bin"
    out_dir.mkdir(parents=True, exist_ok=True)
    canonical = out_dir / "ffmpeg.exe"
    if not canonical.is_file() or canonical.stat().st_size != src.stat().st_size:
        shutil.copy2(src, canonical)
    return canonical


def spec_source(mode: str, ffmpeg: Path, icon: Path) -> str:
    onefile = mode == "standalone"
    name = "VoxScribe-Standalone" if onefile else "VoxScribe"
    model_datas = ""
    if onefile:
        import json
        entries = []
        bundled = []
        for rel in LIGHT_MODEL_FILES:
            if rel == "manifest.json":
                continue
            src = MODELS / rel
            if src.is_file():
                entries.append(f"    (r'{src.as_posix()}', 'models/{Path(rel).parent.as_posix()}'),")
                bundled.append(rel)
        # A one-file build must ship a manifest that only lists the files it
        # actually contains, otherwise integrity checking reports the missing
        # Qwen3 weights as corruption.
        full = json.loads((MODELS / "manifest.json").read_text(encoding="utf-8"))
        light = {"generator": "VoxScribe scripts/build.py (light bundle)",
                 "files": {k: v for k, v in full["files"].items() if k in bundled}}
        BUILD.mkdir(exist_ok=True)
        light_dir = BUILD / "light_models"
        light_dir.mkdir(exist_ok=True)
        light_manifest = light_dir / "manifest.json"
        light_manifest.write_text(json.dumps(light, ensure_ascii=False, indent=2),
                                  encoding="utf-8")
        entries.append(f"    (r'{light_manifest.as_posix()}', 'models'),")
        model_datas = "\n" + "\n".join(entries) + "\n"

    collect = f'''# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by scripts/build.py - DO NOT EDIT BY HAND.
from PyInstaller.utils.hooks import collect_all

datas = [(r"{ffmpeg.as_posix()}", "."), (r"{icon.as_posix()}", "resources")]
binaries = []
hiddenimports = []
for _pkg in ("sherpa_onnx", "soundfile", "sounddevice", "pylnk3"):
    _d, _b, _h = collect_all(_pkg)
    datas += _d
    binaries += _b
    hiddenimports += _h
hiddenimports += [
    "win32com.client", "pythoncom", "pywintypes", "win32api", "win32con",
    "PySide6.QtCore", "PySide6.QtGui", "PySide6.QtWidgets",
    "numpy", "pkg_resources",
]
datas += [{model_datas}]

a = Analysis(
    [r"{ENTRY.as_posix()}"],
    pathex=[r"{SRC.as_posix()}"],
    binaries=binaries, datas=datas, hiddenimports=hiddenimports,
    hookspath=[], hooksconfig={{}}, runtime_hooks=[],
    excludes=["pytest", "pyttsx3", "edge_tts", "matplotlib", "tkinter",
              "scipy", "pandas", "IPython", "jupyter"],
    win_no_prefer_redirects=False, win_private_assemblies=False,
    noarchive=False,
)
pyz = PYZ(a.pure, a.zipped_data, cipher=None)
'''

    if onefile:
        collect += f'''
exe = EXE(
    pyz, a.scripts, a.binaries, a.zipfiles, a.datas, [],
    name="{name}", debug=False, bootloader_ignore_signals=False,
    strip=False, upx=False, upx_exclude=[], runtime_tmpdir=None,
    console=True, disable_windowed_traceback=False,
    argv_emulation=False, target_arch=None, codesign_identity=None,
    entitlements_file=None, icon=r"{icon.as_posix()}",
)
'''
    else:
        collect += f'''
exe = EXE(
    pyz, a.scripts, [], exclude_binaries=True, name="{name}",
    debug=False, bootloader_ignore_signals=False, strip=False,
    upx=False, console=True, icon=r"{icon.as_posix()}",
)
coll = COLLECT(
    exe, a.binaries, a.zipfiles, a.datas,
    strip=False, upx=False, upx_exclude=[], name="{name}",
)
'''
    return collect


def _archive_existing_output(output: Path) -> None:
    """Move a previous onedir build aside instead of letting PyInstaller delete it.

    PyInstaller removes the whole output tree when COLLECT is rebuilt.  Moving
    it aside is both safer (user-added files are preserved) and friendlier to
    environments that guard bulk deletions.  Nothing is ever deleted here.
    """
    if not output.exists():
        return
    stamp = time.strftime("%Y%m%d-%H%M%S")
    backup = output.parent / f"{output.name}_previous_{stamp}"
    if backup.exists():
        backup = output.parent / f"{output.name}_previous_{stamp}_{os.getpid()}"
    try:
        output.rename(backup)
        print(f"Previous build preserved at: {backup}")
    except OSError as exc:
        raise SystemExit(f"Cannot archive existing build output {output}: {exc}")


def run_pyinstaller(mode: str) -> Path:
    ffmpeg = ensure_ffmpeg()
    icon = ensure_icon()
    BUILD.mkdir(exist_ok=True)
    DIST.mkdir(exist_ok=True)
    spec = BUILD / f"{mode}.spec"
    spec.write_text(spec_source(mode, ffmpeg, icon), encoding="utf-8")
    work = BUILD / "work" / mode
    dist = DIST / mode
    dist.mkdir(parents=True, exist_ok=True)
    if mode == "portable":
        _archive_existing_output(dist / "VoxScribe")
    cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
           "--workpath", str(work), "--distpath", str(dist), str(spec)]
    print("Running:", " ".join(cmd))
    subprocess.run(cmd, check=True, cwd=str(ROOT))
    return dist


def build_standalone() -> Path:
    dist = run_pyinstaller("standalone")
    exe = dist / "VoxScribe-Standalone.exe"
    if not exe.is_file():
        raise SystemExit(f"EXE not produced: {exe}")
    print(f"Standalone EXE: {exe} ({exe.stat().st_size / 1048576:.1f} MB)")
    return exe


def build_portable() -> Path:
    dist = run_pyinstaller("portable")
    out = dist / "VoxScribe"
    if not (out / "VoxScribe.exe").is_file():
        raise SystemExit(f"EXE not produced: {out}")
    # Ship all engines (including Qwen3) next to the EXE.
    target_models = out / "models"
    if target_models.exists():
        shutil.rmtree(target_models)
    shutil.copytree(MODELS, target_models,
                    ignore=shutil.ignore_patterns("_downloads", "*.part"))
    # The spec already bundles ffmpeg.exe as a PyInstaller data file, which in
    # onedir mode lands in _internal/.  Copying a second copy next to the EXE
    # wasted ~105 MB per download and was never preferred by paths.ffmpeg_path().
    # Keep a defensive fallback for PyInstaller versions that place datas
    # directly in the output directory instead of _internal/.
    internal_ffmpeg = out / "_internal" / "ffmpeg.exe"
    root_ffmpeg = out / "ffmpeg.exe"
    if not internal_ffmpeg.is_file() and not root_ffmpeg.is_file():
        shutil.copy2(ensure_ffmpeg(), root_ffmpeg)
    (out / "使用说明.txt").write_text(
        "双击 VoxScribe.exe 即可运行，无需安装 Python 或任何运行环境。\n"
        "首次运行会在桌面创建快捷方式；右键快捷方式 -> 打开文件所在位置可定位到本目录。\n"
        "models 与 _internal 目录内为离线识别模型和运行库，请勿删除或单独移动 EXE。\n",
        encoding="utf-8-sig")
    zip_path = DIST / "VoxScribe-Portable-win64.zip"
    entries = 0
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in out.rglob("*"):
            if f.is_file():
                z.write(f, f.relative_to(out.parent))
                entries += 1
    print(f"Portable folder: {out}")
    print(f"Portable ZIP: {zip_path} ({zip_path.stat().st_size / 1048576:.1f} MB, "
          f"{entries} files, ffmpeg copies: "
          f"{sum(1 for p in (internal_ffmpeg, root_ffmpeg) if p.is_file())})")
    return zip_path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=("standalone", "portable", "all"), default="all")
    args = ap.parse_args()
    if not (MODELS / "manifest.json").is_file():
        # Continuing here only delayed the failure to spec_source()'s
        # read_text(), after the user had already waited through a build.
        raise SystemExit(
            "缺少 models/manifest.json：请先运行 scripts/download_models.py 下载模型")
    if args.mode in ("standalone", "all"):
        build_standalone()
    if args.mode in ("portable", "all"):
        build_portable()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
